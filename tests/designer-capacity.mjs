import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {sampleProject,LIMITS,parseProject} from '../src/frontend/designer/model.js';
import {BuildingStore,parseBuilding} from '../src/frontend/designer/building-model.js';
const p=sampleProject(),base=p.objects[0];
p.objects=Array.from({length:999},(_,i)=>({...structuredClone(base),id:`object-${i+1}`,x:-30+(i%40)*1.5,z:-25+Math.floor(i/40)*2}));
const store=new BuildingStore(p);
store.execute({type:'addObject',assetId:base.assetId,x:0,z:0});
assert.equal(store.state.objects.length,1000);
const saved=store.serialize();assert.ok(new TextEncoder().encode(saved).length>256*1024);
assert.equal(parseBuilding(saved).levels[0].design.objects.length,1000);
assert.equal(parseProject(JSON.stringify(store.state)).objects.length,1000);
assert.throws(()=>store.execute({type:'addObject',assetId:base.assetId,x:0,z:0}));assert.equal(store.serialize(),saved);
assert.throws(()=>store.execute({type:'objects.paste',objects:[base],dx:0,dz:0}));assert.equal(store.serialize(),saved);
store.undo();assert.equal(store.state.objects.length,999);store.redo();assert.equal(store.serialize(),saved);
const invalid=JSON.parse(saved);invalid.levels[0].design.objects.push({...base,id:'object-1001'});assert.throws(()=>parseBuilding(JSON.stringify(invalid)));
assert.throws(()=>parseBuilding(' '.repeat(LIMITS.fileBytes+1)),/10 MB/);
writeFileSync('output/capacity-1000-test.json',saved);
console.log(`PASS 1000-object add, save/reopen (${Buffer.byteLength(saved)} bytes), undo/redo; 1001 add/paste/import rejected atomically.`);
