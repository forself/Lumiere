import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {installTestDom} from '../lib/ui_components/common/TreeList/test-dom.mjs';
installTestDom();
const {DesignerPage}=await import('../src/frontend/designer/DesignerPage.js');
const {LIMITS}=await import('../src/frontend/designer/model.js');
const {parseBuilding}=await import('../src/frontend/designer/building-model.js');
const source=readFileSync('output/crossroads-convenience-store.json','utf8');
const exact=source+' '.repeat(LIMITS.fileBytes-Buffer.byteLength(source));
assert.equal(Buffer.byteLength(exact),10485760);
assert.equal(parseBuilding(exact).levels[0].design.objects.length,80);
assert.throws(()=>parseBuilding(exact+' '),/10 MB/);
const page=new DesignerPage();page.sync=()=>{};page.message=v=>{page.notice=v;};page.views=[{fit(){}}];
await page.importFiles([{size:Buffer.byteLength(exact),text:async()=>exact}]);
assert.equal(page.store.state.objects.length,80);assert.match(page.notice,/沒有上傳/);
const before=page.store.serialize();await page.importFiles([{size:LIMITS.fileBytes+1,text:async()=>{throw Error('Must not read');}}]);
assert.equal(page.store.serialize(),before);assert.match(page.notice,/10 MB/);
const prefab=JSON.stringify({format:'lumiere-furniture',version:1,objects:[page.store.state.objects[0]]});
await page.importPrefab({size:LIMITS.fileBytes,text:async()=>prefab+' '.repeat(LIMITS.fileBytes-Buffer.byteLength(prefab))});
assert.match(page.notice,/已載入/);
await page.importPrefab({size:LIMITS.fileBytes+1,text:async()=>{throw Error('Must not read');}});assert.match(page.notice,/10 MB/);
writeFileSync('output/file-limit-10mb-test.json',exact);
console.log('PASS exact 10 MiB design/prefab accepted; +1 byte rejected without reading or altering design. Padding tests byte boundary, not complex-scene performance.');
